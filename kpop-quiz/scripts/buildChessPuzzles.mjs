// Builds src/data/chessPuzzles.ts from the Lichess puzzle export (CC0 public domain:
// "Use them for research, commercial purpose, publication, anything you like").
//
//   node scripts/buildChessPuzzles.mjs                      # streams the CSV from GitHub
//   node scripts/buildChessPuzzles.mjs lichess_db_puzzle.csv # or a local, unzipped official file
//
// The default source is the same CSV kept with Git LFS in github.com/pwenker/chessli2 (used because
// database.lichess.org can be blocked in sandboxes). It is read as a stream; nothing big is stored.
// Every kept puzzle is replayed with chess.js; mate puzzles must end in checkmate.
import { createReadStream, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { Readable } from 'node:stream';
import { Chess } from 'chess.js';

const SOURCE = 'https://media.githubusercontent.com/media/pwenker/chessli2/main/lichess_db_puzzles.csv';
const OUT = new URL('../src/data/chessPuzzles.ts', import.meta.url);

// Must match src/data/chessThemes.ts THEME_PRIORITY.
const THEMES = ['mateIn1', 'mateIn2', 'backRankMate', 'promotion', 'fork', 'skewer', 'pin', 'discoveredAttack', 'hangingPiece'];
const MATE = new Set(['mateIn1', 'mateIn2', 'backRankMate']);
const MIN_RATING = 400;
const MAX_RATING = 1600; // exclusive
const BAND = 100;
const BANDS = (MAX_RATING - MIN_RATING) / BAND; // 12
const PER_BAND = 100; // → ~1,200 puzzles
const CANDIDATES_PER_CELL = 60;
const MAX_HER_MOVES = 4;
const MIN_POPULARITY = 90;
const MIN_PLAYS = 2000;

function replay(fen, moves) {
  try {
    const game = new Chess(fen);
    for (const uci of moves) {
      game.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] });
    }
    return game;
  } catch {
    return null;
  }
}

async function openSource(path) {
  if (path) return createReadStream(path);
  const res = await fetch(SOURCE);
  if (!res.ok || !res.body) throw new Error(`Download failed: ${res.status}`);
  return Readable.fromWeb(res.body);
}

const cells = Array.from({ length: BANDS }, () => Object.fromEntries(THEMES.map(t => [t, []])));
let read = 0;
let kept = 0;
const started = Date.now();

const lines = createInterface({ input: await openSource(process.argv[2]), crlfDelay: Infinity });
for await (const line of lines) {
  if (read++ === 0) continue; // header
  if (read % 500_000 === 0) console.error(`… ${read.toLocaleString()} lines, ${kept} kept, ${Math.round((Date.now() - started) / 1000)} s`);
  const [id, fen, movesStr, ratingStr, , popularityStr, playsStr, themesStr] = line.split(',');
  const rating = Number(ratingStr);
  if (!(rating >= MIN_RATING && rating < MAX_RATING)) continue;
  if (Number(popularityStr) < MIN_POPULARITY || Number(playsStr) < MIN_PLAYS) continue;
  const moves = movesStr.split(' ');
  if (moves.length < 2 || moves.length % 2 !== 0 || moves.length / 2 > MAX_HER_MOVES) continue;
  const tags = new Set(themesStr.split(' '));
  const theme = THEMES.find(t => tags.has(t));
  if (!theme) continue;
  const cell = cells[Math.floor((rating - MIN_RATING) / BAND)][theme];
  if (cell.length >= CANDIDATES_PER_CELL) continue;
  const end = replay(fen, moves);
  if (!end) continue;
  if (MATE.has(theme) && !end.isCheckmate()) continue;
  cell.push({ id, fen, moves: movesStr, rating, theme, popularity: Number(popularityStr) });
  kept++;
}

// Per band: most popular first, taken round-robin across themes so every idea appears.
const chosen = [];
for (const band of cells) {
  for (const t of THEMES) band[t].sort((a, b) => b.popularity - a.popularity);
  const picked = [];
  for (let round = 0; picked.length < PER_BAND && THEMES.some(t => band[t].length > round); round++) {
    for (const t of THEMES) {
      if (picked.length >= PER_BAND) break;
      if (band[t][round]) picked.push(band[t][round]);
    }
  }
  chosen.push(...picked);
}
chosen.sort((a, b) => a.rating - b.rating || a.id.localeCompare(b.id));

const rows = chosen.map(p => `  [${JSON.stringify(p.id)}, ${JSON.stringify(p.fen)}, ${JSON.stringify(p.moves)}, ${p.rating}, '${p.theme}'],`).join('\n');
writeFileSync(OUT, `// Generated by scripts/buildChessPuzzles.mjs — do not edit by hand.
// Chess puzzles from the Lichess puzzle database (database.lichess.org), released under CC0
// (public domain). ${chosen.length} puzzles rated ${MIN_RATING}–${MAX_RATING - 1}, popular (≥ ${MIN_POPULARITY}) and well played (≥ ${MIN_PLAYS} plays),
// at most ${MAX_HER_MOVES} moves for her. Checked by data/chessPuzzles.test.ts.
// Row: [id, FEN before the opponent's move, moves in UCI (the first is the opponent's), rating, theme].
import type { PuzzleTheme } from './chessThemes';

export interface ChessPuzzle {
  id: string;
  fen: string;
  /** UCI moves; moves[0] is the opponent's move that sets the puzzle up, then hers and the replies alternate. */
  moves: string[];
  rating: number;
  theme: PuzzleTheme;
}

const ROWS: [string, string, string, number, PuzzleTheme][] = [
${rows}
];

export const CHESS_PUZZLES: ChessPuzzle[] = ROWS.map(([id, fen, moves, rating, theme]) => ({ id, fen, moves: moves.split(' '), rating, theme }));
`);
const perTheme = Object.fromEntries(THEMES.map(t => [t, chosen.filter(p => p.theme === t).length]));
console.error(`Read ${read.toLocaleString()} lines in ${Math.round((Date.now() - started) / 1000)} s; wrote ${chosen.length} puzzles.`, perTheme);
