// Truth or Dare cards for the party game. G-rated, kind and silly, for ages 8–12
// playing together on one iPad (works with grown-ups and little siblings too).
// Every card is done in one turn, in a living room, in about 30 seconds.
// Truths are about the player's own ideas and favourites — never about bodies,
// looks, crushes, secrets or embarrassing moments. Nothing is aimed at another
// player except kind things (compliments, cool nicknames).
// Never rename a card id (they may be saved as "seen" or "favourite").

export type TodPack = 'silly' | 'act' | 'sing' | 'animals' | 'draw' | 'brain' | 'family' | 'halloween';
export type TodKind = 'truth' | 'dare' | 'everyone' | 'double';
export type TodLevel = 1 | 2 | 3; // 1 = 🌱 Easy, 2 = 🔥 Brave, 3 = 🤯 Super brave (sillier, never meaner)

export interface TodCard {
  id: string;
  pack: TodPack;
  kind: TodKind;
  level: TodLevel;
  text: string;
  emoji: string;
  timer?: 10 | 20 | 30;
}

