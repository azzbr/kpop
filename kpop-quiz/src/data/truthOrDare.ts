/** Card maker for one pack: ids are `${pack}-${nn}`. */
const mk =
  (pack: TodPack) =>
  (n: number, kind: TodKind, level: TodLevel, emoji: string, text: string, timer?: 10 | 20 | 30): TodCard => ({
    id: `${pack}-${String(n).padStart(2, '0')}`,
    pack,
    kind,
    level,
    text,
    emoji,
    ...(timer ? { timer } : {}),
  });

